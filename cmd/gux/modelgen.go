func generateDTOFile(path string, data *ModelTemplateData) error {
	var buf bytes.Buffer

	// Write header
	buf.WriteString("// Code generated by gux model; DO NOT EDIT.\npackage dto\n\n")

	// Always import time since Detail DTO includes CreatedAt/UpdatedAt
	buf.WriteString("import (\n\t\"time\"\n")
	if data.HasFileFields {
		buf.WriteString("\n\t\"github.com/dougbarrett/gux/core\"\n")
	}
	buf.WriteString(")\n\n")

	// Write List DTO
	buf.WriteString(fmt.Sprintf("// %sList is the DTO for %s list responses.\n", data.Name, data.NameLower))
	buf.WriteString(fmt.Sprintf("type %sList struct {\n", data.Name))
	buf.WriteString(fmt.Sprintf("\tID uint `json:\"id\" gux:\"%s.ID\"`\n", data.Name))
	for _, field := range data.TableFields {
		// For relations, use the preload name as the DTO field name
		dtoFieldName := field.Name
		if field.Preload != "" {
			dtoFieldName = field.Preload
		}
		tag := fmt.Sprintf("`json:\"%s\" gux:\"%s.%s\"", field.JSONName, data.Name, field.Name)
		if field.Preload != "" {
			tag += fmt.Sprintf(" preload:\"%s\"", field.Preload)
		}
		tag += "`"
		buf.WriteString(fmt.Sprintf("\t%s %s %s\n", dtoFieldName, field.DTOType, tag))
	}
	// Add auth-specific fields to DTO (exclude PasswordHash)
	if data.IsAuthModel {
		for _, authField := range data.AuthFields {
			if authField.Name != "PasswordHash" {
				buf.WriteString(fmt.Sprintf("\t%s %s `json:\"%s\" gux:\"%s.%s\"`\n",
					authField.Name, authField.Type, ToSnakeCase(authField.Name), data.Name, authField.Name))
			}
		}
	}
	buf.WriteString("}\n\n")

	// Write Detail DTO
	buf.WriteString(fmt.Sprintf("// %sDetail is the DTO for single %s responses.\n", data.Name, data.NameLower))
	buf.WriteString(fmt.Sprintf("type %sDetail struct {\n", data.Name))
	buf.WriteString(fmt.Sprintf("\tID uint `json:\"id\" gux:\"%s.ID\"`\n", data.Name))
	for _, field := range data.AllFields {
		// For relations, use the preload name as the DTO field name
		dtoFieldName := field.Name
		if field.Preload != "" {
			dtoFieldName = field.Preload
		}
		tag := fmt.Sprintf("`json:\"%s\" gux:\"%s.%s\"", field.JSONName, data.Name, field.Name)
		if field.Preload != "" {
			tag += fmt.Sprintf(" preload:\"%s\"", field.Preload)
		}
		tag += "`"
		buf.WriteString(fmt.Sprintf("\t%s %s %s\n", dtoFieldName, field.DTOType, tag))
	}
	// Add auth-specific fields to DTO (exclude PasswordHash)
	if data.IsAuthModel {
		for _, authField := range data.AuthFields {
			if authField.Name != "PasswordHash" {
				buf.WriteString(fmt.Sprintf("\t%s %s `json:\"%s\" gux:\"%s.%s\"`\n",
					authField.Name, authField.Type, ToSnakeCase(authField.Name), data.Name, authField.Name))
			}
		}
	}
	buf.WriteString(fmt.Sprintf("\tCreatedAt time.Time `json:\"created_at\" gux:\"%s.CreatedAt\"`\n", data.Name))
	buf.WriteString(fmt.Sprintf("\tUpdatedAt time.Time `json:\"updated_at\" gux:\"%s.UpdatedAt\"`\n", data.Name))
	buf.WriteString("}\n")

	// Brief DTOs are now generated in a shared dto/briefs_gen.go file
	// to prevent duplicate declarations across multiple model files

	return os.WriteFile(path, buf.Bytes(), 0644)
}

// BriefDTOInfo holds information needed to generate a Brief DTO
type BriefDTOInfo struct {
	Model        string
	DisplayField string
}

// GenerateSharedBriefsFile generates guxgen/dto/briefs_gen.go with all Brief DTOs
// This prevents duplicate Brief DTO declarations across model files
func GenerateSharedBriefsFile(briefs map[string]BriefDTOInfo) error {
	if len(briefs) == 0 {
		return nil
	}

	// Ensure guxgen/dto directory exists
	if err := os.MkdirAll(filepath.Join("guxgen", "dto"), 0755); err != nil {
		return fmt.Errorf("create guxgen/dto directory: %w", err)
	}

	// Check for existing types in manual dto/ directory (backwards compat)
	existingTypes := findExistingDTOTypes("dto")

	var buf bytes.Buffer
	buf.WriteString("// Code generated by gux gen; DO NOT EDIT.\n")
	buf.WriteString("// This file contains Brief DTOs shared across all models.\n")
	buf.WriteString("package dto\n\n")

	// Sort keys for consistent output
	var models []string
	for model := range briefs {
		models = append(models, model)
	}
	sort.Strings(models)

	generated := 0
	for _, model := range models {
		briefTypeName := model + "Brief"
		if existingTypes[briefTypeName] {
			continue // Skip - already exists in a manual file
		}

		info := briefs[model]
		displayField := info.DisplayField
		if displayField == "" {
			displayField = "Name"
		}

		buf.WriteString(fmt.Sprintf("// %sBrief is a simplified %s DTO for embedding.\n", model, strings.ToLower(model)))
		buf.WriteString(fmt.Sprintf("type %sBrief struct {\n", model))
		buf.WriteString(fmt.Sprintf("\tID   uint   `json:\"id\" gux:\"%s.ID\"`\n", model))
		buf.WriteString(fmt.Sprintf("\t%s string `json:\"%s\" gux:\"%s.%s\"`\n", displayField, ToSnakeCase(displayField), model, displayField))
		buf.WriteString("}\n\n")
		generated++
	}

	if generated == 0 {
		// All Brief types exist in manual files, remove generated file if it exists
		os.Remove(filepath.Join("guxgen", "dto", "briefs_gen.go"))
		return nil
	}

	return os.WriteFile(filepath.Join("guxgen", "dto", "briefs_gen.go"), buf.Bytes(), 0644)
}

// findExistingDTOTypes scans the dto directory for existing type declarations
func findExistingDTOTypes(dtoDir string) map[string]bool {
	types := make(map[string]bool)

	files, err := os.ReadDir(dtoDir)
	if err != nil {
		return types // Directory may not exist yet
	}

	for _, file := range files {
		if file.IsDir() || !strings.HasSuffix(file.Name(), ".go") {
			continue
		}
		// Skip generated files (we'll regenerate them)
		if strings.HasSuffix(file.Name(), "_gen.go") {
			continue
		}

		content, err := os.ReadFile(filepath.Join(dtoDir, file.Name()))
		if err != nil {
			continue
		}

		// Simple regex to find type declarations
		// Matches: type TypeName struct
		lines := strings.Split(string(content), "\n")
		for _, line := range lines {
			line = strings.TrimSpace(line)
			if strings.HasPrefix(line, "type ") && strings.Contains(line, " struct") {
				parts := strings.Fields(line)
				if len(parts) >= 2 {
					types[parts[1]] = true
				}
			}
		}
	}

	return types
}

// toDisplayName converts CamelCase/PascalCase to human-readable format
// "LeadSources" -> "Lead Sources", "UserID" -> "User ID"
func toDisplayName(s string) string {
	if s == "" {
		return s
	}
	var result strings.Builder
	for i, r := range s {
		if i > 0 && r >= 'A' && r <= 'Z' {
			result.WriteRune(' ')
		}
		result.WriteRune(r)
	}
	return result.String()
}

// getInitials extracts up to 2 initials from a name
// "John Doe" -> "JD", "Alice" -> "A", "john smith" -> "JS"
func getInitials(name string) string {
	if name == "" {
		return "?"
	}
	words := strings.Fields(name)
	if len(words) == 0 {
		return string([]rune(name)[0])
	}
	if len(words) == 1 {
		runes := []rune(words[0])
		if len(runes) > 0 {
			return strings.ToUpper(string(runes[0]))
		}
		return "?"
	}
	first := []rune(words[0])
	last := []rune(words[len(words)-1])
	if len(first) > 0 && len(last) > 0 {
		return strings.ToUpper(string(first[0]) + string(last[0]))
	}
	return "?"
}

func executeTemplate(tmplText, path string, data *ModelTemplateData) error {
	funcMap := template.FuncMap{
		"toDisplayName": toDisplayName,
		"getInitials":   getInitials,
	}
	tmpl, err := template.New("").Funcs(funcMap).Parse(tmplText)
	if err != nil {
		return fmt.Errorf("parse template: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return fmt.Errorf("execute template: %w", err)
	}

	return os.WriteFile(path, buf.Bytes(), 0644)
}

// executeSimpleTemplate writes a template that doesn't require any data
func executeSimpleTemplate(tmplText, path string) error {
	return os.WriteFile(path, []byte(tmplText), 0644)
}

