func generateDTOFile(path string, data *ModelTemplateData) error {
	// Check which Brief types already exist in the dto package
	existingTypes := findExistingDTOTypes(filepath.Dir(path))

	var buf bytes.Buffer

	// Write header
	buf.WriteString("// Code generated by gux model; DO NOT EDIT.\npackage dto\n\n")

	// Always import time since Detail DTO includes CreatedAt/UpdatedAt
	buf.WriteString("import \"time\"\n\n")

	// Write List DTO
	buf.WriteString(fmt.Sprintf("// %sList is the DTO for %s list responses.\n", data.Name, data.NameLower))
	buf.WriteString(fmt.Sprintf("type %sList struct {\n", data.Name))
	buf.WriteString(fmt.Sprintf("\tID uint `json:\"id\" gux:\"%s.ID\"`\n", data.Name))
	for _, field := range data.TableFields {
		tag := fmt.Sprintf("`json:\"%s\" gux:\"%s.%s\"", field.JSONName, data.Name, field.Name)
		if field.Preload != "" {
			tag += fmt.Sprintf(" preload:\"%s\"", field.Preload)
		}
		tag += "`"
		buf.WriteString(fmt.Sprintf("\t%s %s %s\n", field.Name, field.DTOType, tag))
	}
	buf.WriteString("}\n\n")

	// Write Detail DTO
	buf.WriteString(fmt.Sprintf("// %sDetail is the DTO for single %s responses.\n", data.Name, data.NameLower))
	buf.WriteString(fmt.Sprintf("type %sDetail struct {\n", data.Name))
	buf.WriteString(fmt.Sprintf("\tID uint `json:\"id\" gux:\"%s.ID\"`\n", data.Name))
	for _, field := range data.AllFields {
		tag := fmt.Sprintf("`json:\"%s\" gux:\"%s.%s\"", field.JSONName, data.Name, field.Name)
		if field.Preload != "" {
			tag += fmt.Sprintf(" preload:\"%s\"", field.Preload)
		}
		tag += "`"
		buf.WriteString(fmt.Sprintf("\t%s %s %s\n", field.Name, field.DTOType, tag))
	}
	buf.WriteString(fmt.Sprintf("\tCreatedAt time.Time `json:\"created_at\" gux:\"%s.CreatedAt\"`\n", data.Name))
	buf.WriteString(fmt.Sprintf("\tUpdatedAt time.Time `json:\"updated_at\" gux:\"%s.UpdatedAt\"`\n", data.Name))
	buf.WriteString("}\n")

	// Write Brief DTOs for relations (only if they don't already exist)
	for _, rel := range data.Relations {
		briefTypeName := rel.Model + "Brief"
		if existingTypes[briefTypeName] {
			continue // Skip - already exists in another file
		}
		buf.WriteString(fmt.Sprintf("\n// %sBrief is a simplified %s DTO for embedding.\n", rel.Model, strings.ToLower(rel.Model)))
		buf.WriteString(fmt.Sprintf("type %sBrief struct {\n", rel.Model))
		buf.WriteString(fmt.Sprintf("\tID   uint   `json:\"id\" gux:\"%s.ID\"`\n", rel.Model))
		buf.WriteString(fmt.Sprintf("\tName string `json:\"name\" gux:\"%s.Name\"`\n", rel.Model))
		buf.WriteString("}\n")
	}

	return os.WriteFile(path, buf.Bytes(), 0644)
}

// findExistingDTOTypes scans the dto directory for existing type declarations
func findExistingDTOTypes(dtoDir string) map[string]bool {
	types := make(map[string]bool)

	files, err := os.ReadDir(dtoDir)
	if err != nil {
		return types // Directory may not exist yet
	}

	for _, file := range files {
		if file.IsDir() || !strings.HasSuffix(file.Name(), ".go") {
			continue
		}
		// Skip generated files (we'll regenerate them)
		if strings.HasSuffix(file.Name(), "_gen.go") {
			continue
		}

		content, err := os.ReadFile(filepath.Join(dtoDir, file.Name()))
		if err != nil {
			continue
		}

		// Simple regex to find type declarations
		// Matches: type TypeName struct
		lines := strings.Split(string(content), "\n")
		for _, line := range lines {
			line = strings.TrimSpace(line)
			if strings.HasPrefix(line, "type ") && strings.Contains(line, " struct") {
				parts := strings.Fields(line)
				if len(parts) >= 2 {
					types[parts[1]] = true
				}
			}
		}
	}

	return types
}

func executeTemplate(tmplText, path string, data *ModelTemplateData) error {
	tmpl, err := template.New("").Parse(tmplText)
	if err != nil {
		return fmt.Errorf("parse template: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return fmt.Errorf("execute template: %w", err)
	}

	return os.WriteFile(path, buf.Bytes(), 0644)
}
