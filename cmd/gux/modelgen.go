// TemplateField represents a field for template rendering
type TemplateField struct {
	Name         string
	Type         string
	GoType       string
	DTOType      string
	JSONName     string
	Label        string
	GormTag      string
	StateVar     string
	StateType    string
	StateName    string
	StateDefault string
	DataValue    string
	EmptyValue   string
	FormField    string
	DetailField  string
	Preload      string
	IsRelation   bool
	IsBool       bool
	IsTime       bool
	IsSlice      bool
	Badge        *BadgeConfig
}

// TemplateSection represents a section for template rendering
type TemplateSection struct {
	Name   string
	Fields []TemplateField
}

// TemplateRelation represents a relation for template rendering
type TemplateRelation struct {
	VarName     string
	Model       string
	ModelPlural string
	Label       string
}

// ModelTemplateData holds all data for model template rendering
type ModelTemplateData struct {
	Name            string
	NameLower       string
	NamePlural      string
	NamePluralLower string
	RoutePlural     string
	ModulePath      string
	Sections        []TemplateSection
	TableFields     []TemplateField
	AllFields       []TemplateField
	RequiredFields  []TemplateField
	Relations       []TemplateRelation
	SectionedFields map[string][]TemplateField
	HasTime         bool
	HasJSON         bool
	HasRelations    bool
	DisplayField    string
}

// GenerateModelFilesImpl generates all files for a model definition
func GenerateModelFilesImpl(model *ModelDefinition, optionSets map[string]OptionSet, modulePath string) error {
	// Prepare template data
	data := prepareModelTemplateData(model, modulePath)

	// Create directories if needed
	dirs := []string{"models", "dto", "admin"}
	for _, dir := range dirs {
		if err := os.MkdirAll(dir, 0755); err != nil {
			return fmt.Errorf("create directory %s: %w", dir, err)
		}
	}

	// Generate model file
	modelPath := filepath.Join("models", ToSnakeCase(model.Name)+"_gen.go")
	if err := executeTemplate(ModelGenTemplates.Model, modelPath, data); err != nil {
		return fmt.Errorf("generate model: %w", err)
	}
	fmt.Printf("  %s\n", modelPath)

	// Generate DTO file
	dtoPath := filepath.Join("dto", ToSnakeCase(model.Name)+"_gen.go")
	if err := generateDTOFile(dtoPath, data); err != nil {
		return fmt.Errorf("generate dto: %w", err)
	}
	fmt.Printf("  %s\n", dtoPath)

	// Generate admin list page
	listPath := filepath.Join("admin", ToSnakeCase(ToPlural(model.Name))+"_gen.go")
	if err := executeTemplate(ModelGenTemplates.AdminList, listPath, data); err != nil {
		return fmt.Errorf("generate admin list: %w", err)
	}
	fmt.Printf("  %s\n", listPath)

	// Generate admin new page
	newPath := filepath.Join("admin", ToSnakeCase(model.Name)+"_new_gen.go")
	if err := executeTemplate(ModelGenTemplates.AdminNew, newPath, data); err != nil {
		return fmt.Errorf("generate admin new: %w", err)
	}
	fmt.Printf("  %s\n", newPath)

	// Generate admin detail page
	detailPath := filepath.Join("admin", ToSnakeCase(model.Name)+"_detail_gen.go")
	if err := executeTemplate(ModelGenTemplates.AdminDetail, detailPath, data); err != nil {
		return fmt.Errorf("generate admin detail: %w", err)
	}
	fmt.Printf("  %s\n", detailPath)

	return nil
}

func prepareModelTemplateData(model *ModelDefinition, modulePath string) *ModelTemplateData {
	data := &ModelTemplateData{
		Name:            model.Name,
		NameLower:       strings.ToLower(model.Name),
		NamePlural:      ToPlural(model.Name),
		NamePluralLower: strings.ToLower(ToPlural(model.Name)),
		RoutePlural:     ToSnakeCase(ToPlural(model.Name)),
		ModulePath:      modulePath,
		SectionedFields: make(map[string][]TemplateField),
		DisplayField:    "Name", // Default display field
	}

	// Process sections and fields
	for sectionName, fields := range model.Sections {
		var sectionFields []TemplateField

		for _, field := range fields {
			tf := convertToTemplateField(&field, model.Name)
			sectionFields = append(sectionFields, tf)
			data.AllFields = append(data.AllFields, tf)

			if field.Table {
				data.TableFields = append(data.TableFields, tf)
			}

			if field.Required {
				data.RequiredFields = append(data.RequiredFields, tf)
			}

			if field.Relation != "" {
				data.HasRelations = true
				data.Relations = append(data.Relations, TemplateRelation{
					VarName:     strings.ToLower(field.Relation) + "s",
					Model:       field.Relation,
					ModelPlural: ToPlural(field.Relation),
					Label:       getLabel(field),
				})
			}

			if tf.IsTime {
				data.HasTime = true
			}
			if tf.IsSlice && tf.Type == "[]string" {
				data.HasJSON = true
			}
		}

		data.Sections = append(data.Sections, TemplateSection{
			Name:   sectionName,
			Fields: sectionFields,
		})
		data.SectionedFields[sectionName] = sectionFields
	}

	return data
}

func convertToTemplateField(field *ModelField, modelName string) TemplateField {
	tf := TemplateField{
		Name:       field.Name,
		Type:       field.Type,
		GoType:     field.Type,
		DTOType:    field.Type,
		JSONName:   ToSnakeCase(field.Name),
		Label:      getLabel(*field),
		IsRelation: field.Relation != "",
		IsBool:     field.Type == "bool",
		IsTime:     field.Type == "time.Time" || field.Type == "*time.Time",
		IsSlice:    IsSliceType(field.Type),
		Badge:      field.Badge,
	}

	// Generate GORM tag
	tf.GormTag = generateGormTag(field)

	// Generate state helpers
	tf.StateVar = strings.ToLower(field.Name[:1]) + field.Name[1:] + "State"
	tf.StateName = ToSnakeCase(field.Name)

	switch field.Type {
	case "string":
		tf.StateType = "String"
		tf.StateDefault = `""`
		tf.EmptyValue = `""`
		tf.DataValue = tf.StateVar + ".Get()"
	case "int", "uint":
		tf.StateType = "String"
		tf.StateDefault = `""`
		tf.EmptyValue = `""`
		tf.DataValue = fmt.Sprintf("parseUint(%s.Get())", tf.StateVar)
	case "*uint":
		tf.StateType = "String"
		tf.StateDefault = `""`
		tf.EmptyValue = `""`
		tf.DataValue = fmt.Sprintf("parseUintPtr(%s.Get())", tf.StateVar)
		tf.DTOType = fmt.Sprintf("*%sBrief", field.Relation) // No dto. prefix - same package
		tf.Preload = strings.TrimSuffix(field.Name, "ID")
	case "bool":
		tf.StateType = "Bool"
		tf.StateDefault = "false"
		tf.EmptyValue = "false"
		tf.DataValue = tf.StateVar + ".Get()"
	case "time.Time":
		tf.StateType = "String"
		tf.StateDefault = `""`
		tf.EmptyValue = `""`
		tf.DataValue = fmt.Sprintf("parseTime(%s.Get())", tf.StateVar)
	case "*time.Time":
		tf.StateType = "String"
		tf.StateDefault = `""`
		tf.EmptyValue = `""`
		tf.DataValue = fmt.Sprintf("parseTimePtr(%s.Get())", tf.StateVar)
	case "[]string":
		tf.StateType = "String"
		tf.StateDefault = `"[]"`
		tf.EmptyValue = `"[]"`
		tf.DataValue = fmt.Sprintf("parseStringSlice(%s.Get())", tf.StateVar)
		tf.GoType = "StringList"
	default:
		if IsSliceType(field.Type) && field.Relation != "" {
			// M2M relation
			tf.StateType = "String"
			tf.StateDefault = `"[]"`
			tf.DTOType = fmt.Sprintf("[]%sBrief", field.Relation) // No dto. prefix - same package
			tf.Preload = field.Name
		}
	}

	// Generate form field code
	tf.FormField = generateFormFieldCode(field, tf)

	// Generate detail field code
	tf.DetailField = generateDetailFieldCode(field, tf)

	return tf
}

func getLabel(field ModelField) string {
	if field.Label != "" {
		return field.Label
	}
	// Convert PascalCase to Title Case with spaces
	var result strings.Builder
	for i, r := range field.Name {
		if i > 0 && r >= 'A' && r <= 'Z' {
			result.WriteRune(' ')
		}
		result.WriteRune(r)
	}
	return result.String()
}

func generateGormTag(field *ModelField) string {
	var tags []string

	if field.Required {
		tags = append(tags, "not null")
	}

	if field.Type == "[]string" {
		tags = append(tags, "type:json")
	}

	if field.Many2Many != "" {
		tags = append(tags, fmt.Sprintf("many2many:%s", field.Many2Many))
	}

	if field.Relation != "" && !IsSliceType(field.Type) {
		// FK field - no special tag needed, GORM handles it
	}

	jsonTag := fmt.Sprintf(`json:"%s"`, ToSnakeCase(field.Name))

	if len(tags) > 0 {
		return fmt.Sprintf("`%s gorm:\"%s\"`", jsonTag, strings.Join(tags, ";"))
	}
	return fmt.Sprintf("`%s`", jsonTag)
}

